package com.swiftroute.orderservice.entity;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

import com.swiftroute.orderservice.entity.enums.PlanStatus;
import com.swiftroute.orderservice.entity.enums.PlanTriggerType;

import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Represents a route optimization plan generated by the routing engine and
 * managed through its full lifecycle inside the Order Service.
 *
 * <p>The plan is the authoritative record of which orders are grouped together,
 * which driver is assigned, and what the optimized route looks like.
 *
 * <p>State machine: DRAFT → APPROVED → DISPATCHED (or CANCELLED at any point).
 */
@Entity
@Table(name = "dispatch_plans")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class DispatchPlan {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "plan_id", updatable = false, nullable = false)
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "tenant_id", nullable = false)
    private Tenant tenant;

    @Enumerated(EnumType.STRING)
    @Column(name = "plan_status", nullable = false, length = 20)
    @Builder.Default
    private PlanStatus planStatus = PlanStatus.DRAFT;

    /** Logical reference to driver-service — no physical FK. */
    @Column(name = "driver_id")
    private UUID driverId;

    /** Algorithm identifier returned by the routing engine. */
    @Column(name = "algorithm_used", length = 60)
    private String algorithmUsed;

    /**
     * Full route waypoints JSON returned by the routing engine.
     * Stored as text to avoid mapping complexity; parsed at read time when needed.
     */
    @Column(name = "route_waypoints", columnDefinition = "jsonb")
    private String routeWaypoints;

    @Column(name = "total_distance_km", precision = 10, scale = 3)
    private BigDecimal totalDistanceKm;

    @Column(name = "estimated_duration_minutes")
    private Integer estimatedDurationMinutes;

    @Enumerated(EnumType.STRING)
    @Column(name = "trigger_type", length = 30)
    private PlanTriggerType triggerType;

    /** Whether this plan required manual approval per tenant dispatch config. */
    @Column(name = "requires_approval", nullable = false)
    @Builder.Default
    private Boolean requiresApproval = false;

    /** Deadline by which the driver must acknowledge. Null if not yet dispatched. */
    @Column(name = "ack_deadline_at", columnDefinition = "TIMESTAMPTZ")
    private Instant ackDeadlineAt;

    @Column(name = "acknowledged_at", columnDefinition = "TIMESTAMPTZ")
    private Instant acknowledgedAt;

    @Column(name = "declined_at", columnDefinition = "TIMESTAMPTZ")
    private Instant declinedAt;

    @Column(name = "decline_reason", length = 500)
    private String declineReason;

    @Column(name = "reassignment_count", nullable = false)
    @Builder.Default
    private Short reassignmentCount = 0;

    @Column(name = "planned_at", columnDefinition = "TIMESTAMPTZ")
    private Instant plannedAt;

    @Column(name = "approved_at", columnDefinition = "TIMESTAMPTZ")
    private Instant approvedAt;

    /** Logical reference to auth_db.users — the operator who approved this plan. */
    @Column(name = "approved_by")
    private UUID approvedBy;

    @Column(name = "dispatched_at", columnDefinition = "TIMESTAMPTZ")
    private Instant dispatchedAt;

    @Column(name = "cancelled_at", columnDefinition = "TIMESTAMPTZ")
    private Instant cancelledAt;

    @Column(name = "cancel_reason", length = 500)
    private String cancelReason;

    /** Orders linked to this plan in optimised stop order. */
    @OneToMany(mappedBy = "plan", cascade = CascadeType.ALL, orphanRemoval = true, fetch = FetchType.LAZY)
    @Builder.Default
    private List<DispatchPlanOrder> planOrders = new ArrayList<>();

    @Column(name = "created_at", nullable = false, updatable = false, columnDefinition = "TIMESTAMPTZ")
    @Builder.Default
    private Instant createdAt = Instant.now();

    @Column(name = "updated_at", nullable = false, columnDefinition = "TIMESTAMPTZ")
    @Builder.Default
    private Instant updatedAt = Instant.now();

    @Version
    @Column(name = "version", nullable = false)
    @Builder.Default
    private Long version = 0L;

    // -------------------------------------------------------------------------
    // State transition helpers — validation is enforced in service layer
    // -------------------------------------------------------------------------

    /**
     * Transitions DRAFT → APPROVED.
     *
     * @param approvedByUserId UUID of the approving operator (may be null for auto-approval)
     * @throws IllegalStateException if current status is not DRAFT
     */
    public void approve(UUID approvedByUserId) {
        if (this.planStatus != PlanStatus.DRAFT) {
            throw new IllegalStateException("Plan can only be approved from DRAFT state. Current: " + planStatus);
        }
        this.planStatus = PlanStatus.APPROVED;
        this.approvedAt = Instant.now();
        this.approvedBy = approvedByUserId;
        this.updatedAt = Instant.now();
    }

    /**
     * Transitions APPROVED → DISPATCHED.
     *
     * @param ackDeadline deadline timestamp by which the driver must acknowledge
     * @throws IllegalStateException if current status is not APPROVED
     */
    public void dispatch(Instant ackDeadline) {
        if (this.planStatus != PlanStatus.APPROVED) {
            throw new IllegalStateException("Plan can only be dispatched from APPROVED state. Current: " + planStatus);
        }
        this.planStatus = PlanStatus.DISPATCHED;
        this.dispatchedAt = Instant.now();
        this.ackDeadlineAt = ackDeadline;
        this.updatedAt = Instant.now();
    }

    /**
     * Cancels the plan from any non-terminal state.
     *
     * @param reason human-readable cancellation reason
     * @throws IllegalStateException if plan is already CANCELLED
     */
    public void cancel(String reason) {
        if (this.planStatus == PlanStatus.CANCELLED) {
            throw new IllegalStateException("Plan is already cancelled.");
        }
        this.planStatus = PlanStatus.CANCELLED;
        this.cancelledAt = Instant.now();
        this.cancelReason = reason;
        this.updatedAt = Instant.now();
    }

    /** Records driver acknowledgement for a DISPATCHED plan. */
    public void acknowledge() {
        if (this.planStatus != PlanStatus.DISPATCHED) {
            throw new IllegalStateException("Plan must be DISPATCHED to acknowledge. Current: " + planStatus);
        }
        this.acknowledgedAt = Instant.now();
        this.updatedAt = Instant.now();
    }

    /** Records driver decline for a DISPATCHED plan (triggers reassignment flow). */
    public void decline(String reason) {
        if (this.planStatus != PlanStatus.DISPATCHED) {
            throw new IllegalStateException("Plan must be DISPATCHED to decline. Current: " + planStatus);
        }
        this.declinedAt = Instant.now();
        this.declineReason = reason;
        this.updatedAt = Instant.now();
    }
}

